
from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    Integer,
    String,
    Text
)

from app.database.connection import Base


class Analysis(Base):
    __tablename__ = "analyses"

    # Primary key
    id = Column(Integer, primary_key=True, index=True)

    # Original input
    company = Column(String(100), nullable=False, index=True)
    answer = Column(Text, nullable=False)

    # Brand mention detection
    mentioned = Column(Boolean, nullable=False)

    # Sentiment classification
    sentiment = Column(String(30), nullable=False)
    sentiment_score = Column(Float, nullable=True)

    # Extracted information (JSON serialized as text)
    relevant_context = Column(Text, nullable=False)
    opinions = Column(Text, nullable=False)

    # Explanation generated by Gemini
    explanation = Column(Text, nullable=False)

    # Analysis timestamp (UTC)
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False
    )
